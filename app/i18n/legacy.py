def translate_legacy_text(value: str, locale: str | None) -> str:
    if normalize_locale(locale) != "en-US" or not value:
        return value
    result = value
    for source, target in sorted(LEGACY_EN.items(), key=lambda item: len(item[0]), reverse=True):
        result = result.replace(source, target)
    return result


@pass_context
def legacy_translate_for_template(ctx: Any, value: str) -> str:
    return translate_legacy_text(value, ctx.get("locale"))


class LegacyI18nExtension(Extension):
    """Wrap legacy literal CJK text in a request-locale-aware translator."""

    _jinja_segment = re.compile(r"({{.*?}}|{%.*?%}|{#.*?#})", re.DOTALL)
    _han_phrase = re.compile(r"[\u4e00-\u9fff]+(?:[：，。；、（）【】！？/ -]*[\u4e00-\u9fff]+)*")
    _jinja_han_string = re.compile(r"(?P<quote>['\"])(?P<value>[^'\"]*[\u4e00-\u9fff][^'\"]*)(?P=quote)")

    def preprocess(self, source: str, name: str | None, filename: str | None = None) -> str:
        segments = self._jinja_segment.split(source)
        for index in range(0, len(segments), 2):
            segments[index] = self._han_phrase.sub(
                lambda match: "{{ __legacy(" + repr(match.group(0)) + ") }}",
                segments[index],
            )
        for index in range(1, len(segments), 2):
            if segments[index].startswith("{#"):
                continue
            segments[index] = self._jinja_han_string.sub(
                lambda match: "__legacy(" + repr(match.group("value")) + ")",
                segments[index],
            )
        return "".join(segments)
